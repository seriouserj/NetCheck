from __future__ import annotations

from enum import Enum
from typing import Any


class AppLanguage(str, Enum):
    """Languages available in the NetCheck interface."""

    ENGLISH = "en"
    GERMAN = "de"
    RUSSIAN = "ru"
    UKRAINIAN = "uk"


_current_language = AppLanguage.ENGLISH


def set_language(language: AppLanguage | str) -> None:
    """Select the language used by subsequent UI construction."""
    global _current_language
    _current_language = AppLanguage(language)


def current_language() -> AppLanguage:
    """Return the active interface language."""
    return _current_language


def tr(text: str, /, **values: Any) -> str:
    """Translate an English source string and safely format its placeholders."""
    translated = _TRANSLATIONS.get(_current_language, {}).get(text, text)
    return translated.format(**values) if values else translated


